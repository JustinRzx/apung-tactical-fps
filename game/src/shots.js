// Screenshot staging for ?shot=start|play|end|site. Each pose is deterministic and is rendered two
// frames before the headless capture, so the HUD, weapon model, tracers and banners are all live.
import { PALETTE } from './palette.js';

export function stageShot(name, game) {
  const { state, player, bots, hud, world } = game;
  const atk = bots.bots.filter((b) => b.team === 'attackers');
  const def = bots.bots.filter((b) => b.team === 'defenders');
  const place = (bot, x, y, z, yaw) => game.placeBot(bot, x, y, z, yaw, true, 100);
  const dead = (bot, x, y, z, yaw) => game.placeBot(bot, x, y, z, yaw, false, 0);

  state.paused = false;
  state.hitstop = 0;
  state.trauma = 0;
  state.fovPunch = 0;
  state.started = true;
  state.scoreboardOpen = false;
  state.plantProgress = 0;
  state.beepTimer = 0;
  state.matchOver = false;
  game.clearBomb();
  hud.hideOverlay();
  hud.setPaused(false);
  hud.setArmourBought(false);
  hud.clearBanner();
  hud.scoreboard([], false);
  hud.spectate(null);
  hud.objective(null);
  for (const site of world.sites) site.sign.visible = true;

  if (name === 'start') {
    state.phase = 'buy';
    state.round = 1;
    state.scoreTeal = 0;
    state.scoreAmber = 0;
    state.timer = 15;
    state.plan.attackSite = 'B';
    state.elapsed = 5;
    player.state.kills = 0;
    player.state.deaths = 0;
    player.state.money = 800;
    game.setPlayerAt(-3, 0, 31, -0.02, -0.01);
    player.state.health = 100;
    player.state.armour = 0;
    place(atk[0], -6.5, 0, 27, 0.1);
    place(atk[1], 0.5, 0, 26, -0.06);
    place(atk[2], -4.5, 0, 23.5, 0.1);
    place(atk[3], 1.5, 0, 22, -0.1);
    place(def[0], 5, 0, 5, Math.PI);
    place(def[1], -5, 0, 4, Math.PI * 0.95);
    place(def[2], 24, 0, -8, Math.PI * 0.5);
    place(def[3], -24, 0, -6, Math.PI * 0.55);
    place(def[4], -26, 0.35, -9, Math.PI * 0.5);
    game.setWeapon('pistol');
    hud.banner('RONDE 1', 'OMBAK MENYERANG PURA LAMPION', '', 99);
    hud.radio('OMBAK', 'Rencana: serang Pura Lampion lewat barat.');
  } else if (name === 'play') {
    state.phase = 'live';
    state.round = 8;
    state.scoreTeal = 3;
    state.scoreAmber = 2;
    state.timer = 52;
    state.plan.attackSite = 'A';
    state.elapsed = 41;
    player.state.kills = 2;
    player.state.deaths = 1;
    player.state.money = 2350;
    game.setPlayerAt(20, 0, 8.5, 0, 0.01);
    player.state.health = 74;
    player.state.armour = 38;
    place(atk[0], 19, 0, 12, Math.PI);
    place(atk[1], 23.5, 0, 10, Math.PI * 0.9);
    place(atk[2], 21.5, 0, 0.5, Math.PI);
    place(atk[3], 18, 0, 3, Math.PI * 1.1);
    place(def[0], 20, 0, -2.5, Math.PI);
    place(def[1], 17, 0, -7, Math.PI * 0.9);
    place(def[2], 27, 3, -11, Math.PI * 0.5);
    place(def[3], 28, 0, -14, Math.PI * 0.3);
    dead(def[4], 23, 0, -10, Math.PI);
    game.setWeapon('rifle');
    game.tracer({ x: 20.16, y: 1.5, z: 8.1 }, { x: 20, y: 1.22, z: -2.5 }, PALETTE.teal, 99);
    game.tracer({ x: 20, y: 1.4, z: -2.5 }, { x: 20.4, y: 1.18, z: 7.9 }, PALETTE.amber, 99);
    game.weapon.state.flash = 0.07;
    game.weapon.state.kick = 0.05;
    const rina = bots.bots.find((b) => b.name === 'Rina');
    rina.muzzle = 0.09;
    rina.model.muzzle.visible = true;
    hud.killFeed('Kamu', 'attackers', 'Putri', 'defenders', 'Badak AR');
    hud.radio('Budi', 'Kontak di Dermaga — dua musuh!');
    hud.hitMarker(false);
    state.trauma = 0.22;
  } else if (name === 'end') {
    state.phase = 'over';
    state.round = 13;
    state.scoreTeal = 7;
    state.scoreAmber = 5;
    state.timer = 8;
    state.plan.attackSite = 'A';
    state.elapsed = 61;
    player.state.kills = 18;
    player.state.deaths = 9;
    player.state.money = 9200;
    game.setPlayerAt(26, 0, 0.4, 0, 0.0);
    player.state.health = 63;
    player.state.armour = 25;
    place(atk[0], 23, 0, -5, 0.2);
    place(atk[1], 31, 0, -7, -0.2);
    place(atk[2], 28, 0, -13, 0.3);
    place(atk[3], 27, 3, -11, -0.4);
    dead(def[0], 23, 0, -6, 1.1);
    dead(def[1], 30, 0, -14, 2.0);
    dead(def[2], 21, 0, -9, 0.4);
    dead(def[3], 33, 0, -8, 1.7);
    dead(def[4], 25, 0, -11, 2.5);
    for (const site of world.sites) site.sign.visible = false;
    game.setWeapon('rifle');
    hud.banner('OMBAK MENANG', 'PERTANDINGAN SELESAI · 7 — 5', 'win', 99);
    hud.killFeed('Agus', 'attackers', 'Putri', 'defenders', 'Badak AR');
    hud.radio('Budi', 'Dermaga sudah aman. Menang!');
    state.trauma = 0.08;
  } else if (name === 'site') {
    state.phase = 'live';
    state.round = 9;
    state.scoreTeal = 4;
    state.scoreAmber = 3;
    state.timer = 63;
    state.plan.attackSite = 'B';
    state.elapsed = 17;
    state.plantProgress = 2.2;
    player.state.kills = 3;
    player.state.deaths = 2;
    player.state.money = 3100;
    game.setPlayerAt(-29, 0, -1.0, 0.05, 0.0);
    player.state.health = 88;
    player.state.armour = 50;
    place(atk[0], -21.5, 0.35, -9, 0.4);
    place(atk[1], -33, 0.35, -8, -0.4);
    place(atk[2], -25, 0.35, -13, 0.5);
    place(atk[3], -30, 0.35, -14, -0.5);
    place(def[0], 20, 0, -8, Math.PI);
    place(def[1], 26, 0, -14, Math.PI);
    place(def[2], -20, 0, 2, Math.PI);
    place(def[3], -24, 0, 6, Math.PI);
    dead(def[4], -31.5, 0.35, -15.5, 1.3);
    game.setWeapon('rifle');
    game.bombMesh.visible = true;
    game.bombMesh.position.set(-24.2, 0.48, -7.2);
    hud.objective('MENANAM BOM · PURA LAMPION', 0.63, 'plant');
    hud.killFeed('Sari', 'attackers', 'Rina', 'defenders', 'Cicak');
    hud.radio('Kamu', 'Menanam bom — lindungi aku!');
    state.trauma = 0.05;
  } else {
    state.phase = 'live';
    state.plan.attackSite = 'A';
    game.setPlayerAt(20, 0, 12, 0, 0);
  }

  game.refreshHud();
}
